CREATE TABLE transaction
(
    id             bigint         DEFAULT nextval('hs.transaction_id_seq'::regclass) NOT NULL PRIMARY KEY,
    type           varchar(32)                                                       NOT NULL,
    date           timestamp      DEFAULT CURRENT_TIMESTAMP                          NOT NULL,
    price          numeric(14, 2)                                                    NOT NULL CHECK (price >= 0),
    ad_id          bigint                                                            NOT NULL,
    customer_id    bigint                                                            NOT NULL,
    contract_id    bigint                                                            NOT NULL,
    payment_status varchar(32)    DEFAULT 'PENDING'                                  NOT NULL,
    commission     numeric(14, 2) DEFAULT 0                                          NOT NULL,
    FOREIGN KEY (ad_id) REFERENCES ad ON DELETE RESTRICT,
    FOREIGN KEY (contract_id) REFERENCES contract ON DELETE RESTRICT,
    FOREIGN KEY (customer_id) REFERENCES app_user
);

ALTER TABLE transaction
    OWNER TO postgres;

ALTER SEQUENCE transaction_id_seq OWNED BY transaction.id;

